#!/usr/bin/env python3
"""
Set GATEWAY_IP in the repo .env file.

Single responsibility:
  - Detect this host's primary non-loopback IPv4, or use --ip.
  - Upsert only the GATEWAY_IP line in .env.

It does not start Mosquitto, the firewall, the gateway, or any clients. The
gateway stack orchestration lives in scripts/start_stack.py.
"""

from __future__ import annotations

import argparse
import os
import re
import socket
import subprocess
from pathlib import Path


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def detect_ipv4() -> str | None:
    """Best-effort primary IPv4 (not loopback)."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.settimeout(0.3)
            sock.connect(("8.8.8.8", 80))
            addr, _ = sock.getsockname()
            if addr and not addr.startswith("127."):
                return addr
    except OSError:
        pass

    try:
        result = subprocess.run(
            ["hostname", "-I"],
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        for part in result.stdout.split():
            ip = part.strip()
            if ip and not ip.startswith("127.") and ":" not in ip:
                return ip
    except (OSError, subprocess.TimeoutExpired):
        pass

    try:
        result = subprocess.run(
            ["ip", "-4", "route", "get", "1.1.1.1"],
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
        match = re.search(r"\bsrc\s+(\d+\.\d+\.\d+\.\d+)", result.stdout)
        if match and not match.group(1).startswith("127."):
            return match.group(1)
    except (OSError, subprocess.TimeoutExpired):
        pass

    return None


def upsert_gateway_ip(env_path: Path, ip: str, dry_run: bool = False) -> bool:
    """Upsert GATEWAY_IP=<ip>; return True if the file changed/would change."""
    key = "GATEWAY_IP"
    new_line = f"{key}={ip}\n"

    if env_path.exists():
        text = env_path.read_text(encoding="utf-8")
    else:
        example = env_path.parent / ".env.example"
        if example.exists():
            text = example.read_text(encoding="utf-8")
        else:
            text = "# Generated by scripts/set_gateway_ip_env.py\n"

    lines = text.splitlines(keepends=True)
    found = False
    out: list[str] = []

    for line in lines:
        if re.match(rf"^\s*{re.escape(key)}\s*=", line):
            if not found:
                out.append(new_line)
                found = True
            continue
        out.append(line)

    if not found:
        if text and not text.endswith("\n"):
            out.append("\n")
        out.append(new_line)

    new_text = "".join(out)
    if new_text == text and env_path.exists():
        return False

    if dry_run:
        print(f"[dry-run] would set {key}={ip} in {env_path}")
        return True

    env_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = env_path.parent / f".env.tmp.{os.getpid()}"
    try:
        tmp_path.write_text(new_text, encoding="utf-8")
        os.replace(tmp_path, env_path)
    finally:
        tmp_path.unlink(missing_ok=True)
    return True


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Set only GATEWAY_IP in .env.")
    parser.add_argument("--ip", help="Use this IPv4 instead of auto-detecting")
    parser.add_argument(
        "--env-file",
        type=Path,
        default=repo_root() / ".env",
        help="Path to .env (default: repo root .env)",
    )
    parser.add_argument("--dry-run", action="store_true", help="Print only; do not write")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    ip = args.ip.strip() if args.ip else detect_ipv4()
    if not ip:
        print(
            "Could not detect a non-loopback IPv4. Pass one explicitly, e.g. "
            "--ip 192.168.1.50"
        )
        return 1

    changed = upsert_gateway_ip(args.env_file, ip, args.dry_run)
    if changed:
        print(f"Set GATEWAY_IP={ip} in {args.env_file}")
    else:
        print(f"GATEWAY_IP already set to {ip} in {args.env_file}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
